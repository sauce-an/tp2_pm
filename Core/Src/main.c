		  //Blink_Measurement_LED();
		  SD_log_measurement();

	      //Generate_Fake_Data();
	  	  //Comm_SendTelemetry(); // send to pc every 1 sec
	  	  //Wifi_SendTelemetry(); // send data to PC through Wi-Fi

	      // --- DATA ROUTER & COMS MODE ICON ---
